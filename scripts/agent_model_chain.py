#!/usr/bin/env python3
"""The fleet model chain's ONE source, its rendered lane configs, and its gate (issue #1140).

`agents/model_chain.json` is the ONE definition of the model chain every Hermes fleet lane runs
on: the free primary FIRST, the free fallbacks in list order, the paid pinned model LAST as the
last resort. Since issue #1199 the chain's provider is the built-in **`nous`** provider (the Nous
Portal session; the same `https://inference-api.nousresearch.com/v1` endpoint) and an entry may
carry its OWN `provider`/`base_url` — how the LOCAL Strata engine step rides in the same chain.
`make agent-profile-model-render` renders each fleet lane's Hermes profile config —
`agents/<lane>/config.yaml` — from that file; `make agent-model-chain-check` (bundled into
`make lint`, so `qa-validate`'s `validate` job and `scripts/fix_loop.sh` both run it) refuses a
lane config that drifted from the chain, a chain that lost its primary / fallback / last-resort
shape, a `nous` step that also carries `base_url`/`key_env` (which re-routes it to `custom` and
401s — measured), a last resort that is not the Makefile's `$(HERMES_MODEL)` under
`$(HERMES_ALIAS)`, and any credential VALUE anywhere: every entry names `key_env` and no entry
may carry `api_key` (AGENTS.md rule 3e).

Hermes reads this shape natively (`hermes_cli/model_switch.py::_load_direct_aliases`, documented
in `cli-config.yaml.example`): a `model:` block plus a `model_aliases:` mapping whose entries are
`model` / `provider` / `base_url` / `key_env` (+ `context_window`), so a lane can be switched
along the chain with `-m <alias>` without any custom resolver.

Exit codes: 0 clean, 1 a real problem, 2 the seam could not be read (never a silent clean).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parent.parent
CHAIN_REL = "agents/model_chain.json"
CONFIG_REL = "config.yaml"
LANE_PREFIX = "tll-"

EXIT_OK, EXIT_PROBLEM, EXIT_UNDECIDABLE = 0, 1, 2

ALIAS_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,31}$")
ENV_NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")
MODEL_ID_RE = re.compile(r"^[A-Za-z0-9._-]+/[A-Za-z0-9._:-]+$")
#: A LOCAL engine's model id (the Strata step, issue #1199) is a bare id with no `provider/`
#: prefix — the endpoint it belongs to is the entry's own `base_url`.
LOCAL_MODEL_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]*$")
URL_RE = re.compile(r"^https?://[^\s]+$")
# A credential VALUE must never appear in a chain file or a rendered config: only NAMES do.
CREDENTIAL_KEYS = ("api_key", "apikey", "token", "secret", "password", "authorization")
ROLES = ("primary", "fallback", "last_resort")

GENERATED_HEADER = (
    "# Generated by `make agent-profile-model-render` from agents/model_chain.json (issue #1199).\n"
    "# DO NOT HAND-EDIT: `make agent-model-chain-check` compares this file byte-for-byte with what\n"
    "# the chain renders, and the chain's ORDER is the contract — the free primary first, the free\n"
    "# fallbacks in list order, the pinned paid model LAST as the last resort.\n"
    "# The provider is the built-in `nous` provider (the Nous Portal session); a `nous` step carries\n"
    "# ONLY `provider: nous` — adding `base_url`/`key_env` re-routes it to `custom` and 401s\n"
    "# (measured, issue #1199). A step with its own `provider`/`base_url` is a DIFFERENT endpoint\n"
    "# (the local Strata engine). A credential is a NAME only (AGENTS.md rule 3e): `key_env`, never\n"
    "# a value, and no key's VALUE appears in this file or in any image layer.\n"
)


class Entry(NamedTuple):
    alias: str
    model: str
    role: str
    provider: str
    base_url: str
    key_env: str
    context_window: int
    #: True when the entry carries its OWN `provider`/`base_url` — a DIFFERENT endpoint from the
    #: chain's (the local Strata engine, issue #1199), exempt from the Nous free-tier rule.
    local: bool


class Chain(NamedTuple):
    entries: list[Entry]
    provider: str
    base_url: str
    key_env: str
    measured: dict
    read_problems: list[str]

    @property
    def primary(self) -> Entry | None:
        return next((e for e in self.entries if e.role == "primary"), None)

    @property
    def fallbacks(self) -> list[Entry]:
        return [e for e in self.entries if e.role == "fallback"]

    @property
    def last_resort(self) -> Entry | None:
        return next((e for e in self.entries if e.role == "last_resort"), None)


# -------------------------------------------------------------------------- reads


def read_chain(root: Path) -> tuple[Chain | None, list[str]]:
    """Parse agents/model_chain.json. Returns (chain, fatal) — a fatal means exit 2."""
    path = root / CHAIN_REL
    if not path.is_file():
        return None, f"{CHAIN_REL} is missing — the chain has no source to check"
    try:
        raw = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        return None, f"{CHAIN_REL} is not parseable JSON: {exc}"
    if not isinstance(raw, dict):
        return None, f"{CHAIN_REL} is not a JSON object"

    provider = str(raw.get("provider") or "")
    base_url = str(raw.get("base_url") or "")
    key_env = str(raw.get("key_env") or "")
    measured = raw.get("measured") if isinstance(raw.get("measured"), dict) else {}
    rows = raw.get("chain")
    if not isinstance(rows, list) or not rows:
        return None, f"{CHAIN_REL} carries no `chain` list to read"

    entries: list[Entry] = []
    problems: list[str] = []
    for i, row in enumerate(rows):
        if not isinstance(row, dict):
            problems.append(f"chain[{i}] is not an object")
            continue
        alias = str(row.get("alias") or "").strip().lower()
        model = str(row.get("model") or "").strip()
        role = str(row.get("role") or "").strip()
        # A per-entry `provider` that DIFFERS from the chain's is a DIFFERENT endpoint — the local
        # Strata engine (issue #1199) — and is exempt from the Nous free-tier rule. An absent
        # `provider` inherits the chain's; `base_url`/`key_env` default to the chain's too.
        e_provider = str(row["provider"]) if "provider" in row else provider
        local = e_provider != provider
        e_base = str(row.get("base_url") or "") if "base_url" in row else base_url
        e_key = str(row.get("key_env") or "") if "key_env" in row else key_env
        try:
            context_window = int(row.get("context_window") or 0)
        except (TypeError, ValueError):
            context_window = 0
            problems.append(f"chain[{i}] context_window is not an integer: {row.get('context_window')!r}")
        if not ALIAS_RE.match(alias):
            problems.append(f"chain[{i}] alias is not a lowercase alias name: {alias!r}")
        if not (MODEL_ID_RE.match(model) or (local and LOCAL_MODEL_RE.match(model))):
            problems.append(f"chain[{i}] model is not a provider/model id (or a local engine's "
                            f"bare model id): {model!r}")
        if role not in ROLES:
            problems.append(f"chain[{i}] role {role!r} is not one of {ROLES}")
        for key in CREDENTIAL_KEYS:
            if key in row:
                problems.append(f"chain[{i}] carries a credential field {key!r} — only `key_env` names are allowed")
        entries.append(Entry(alias, model, role, e_provider, e_base, e_key, context_window, local))
    return Chain(entries, provider, base_url, key_env, measured, problems), None


def read_makefile_pins(root: Path) -> tuple[dict[str, str], list[str]]:
    """Read the Makefile's own pins — the values the container alias is written from."""
    path = root / "Makefile"
    if not path.is_file():
        return {}, ["Makefile is missing — the chain cannot be checked against the pins"]
    text = path.read_text()
    pins: dict[str, str] = {}
    problems: list[str] = []
    for name in ("HERMES_MODEL", "HERMES_ALIAS", "NOUS_BASE"):
        m = re.search(rf"^{name}\s*:?=\s*(\S+)", text, re.M)
        if not m:
            problems.append(f"Makefile no longer pins {name}")
        else:
            pins[name] = m.group(1)
    m = re.search(r"model\.aliases\.\$\(HERMES_ALIAS\)\.key_env\s+(\S+)", text)
    if not m:
        problems.append("Makefile no longer writes model.aliases.$(HERMES_ALIAS).key_env")
    else:
        pins["ALIAS_KEY_ENV"] = m.group(1)
    m = re.search(r"model\.aliases\.\$\(HERMES_ALIAS\)\.provider\s+(\S+)", text)
    if not m:
        problems.append("Makefile no longer writes model.aliases.$(HERMES_ALIAS).provider")
    else:
        pins["ALIAS_PROVIDER"] = m.group(1)
    return pins, problems


def fleet_lanes(root: Path) -> list[str]:
    """The fleet lanes, DERIVED from the tree (never a hand-kept list): every agents/tll-* lane."""
    agents = root / "agents"
    if not agents.is_dir():
        return []
    return sorted(
        d.name for d in agents.iterdir()
        if d.is_dir() and d.name.startswith(LANE_PREFIX) and (d / "SOUL.md").is_file()
    )


# ----------------------------------------------------------------------- contract


def chain_problems(chain: Chain, pins: dict[str, str]) -> list[str]:
    """Every way the chain itself can fail its contract."""
    problems: list[str] = list(chain.read_problems)
    entries = chain.entries
    if not entries:
        return ["the chain is empty"]

    primaries = [e for e in entries if e.role == "primary"]
    if len(primaries) != 1:
        problems.append(f"the chain must carry exactly one role=primary, found {len(primaries)}")
    fallbacks = [e for e in entries if e.role == "fallback"]
    if not fallbacks:
        problems.append("the chain must carry at least one role=fallback — a chain with no fallback is a single point of failure")
    last_resorts = [e for e in entries if e.role == "last_resort"]
    if len(last_resorts) != 1:
        problems.append(f"the chain must carry exactly one role=last_resort, found {len(last_resorts)}")
    if last_resorts and entries[-1].role != "last_resort":
        problems.append("the last resort must be the LAST entry in the chain — a paid model may never sit before a free one")

    seen: set[str] = set()
    for i, e in enumerate(entries):
        if e.alias in seen:
            problems.append(f"chain[{i}] alias {e.alias!r} is used twice")
        seen.add(e.alias)
        if not e.model:
            problems.append(f"chain[{i}] ({e.alias}) names no model")
        if not e.context_window:
            problems.append(f"chain[{i}] ({e.alias}) names no context_window")
        # The free-tier rule binds a step on the CHAIN's provider. A step with its own
        # `provider`/`base_url` is a DIFFERENT endpoint (the local Strata engine, issue #1199)
        # and is exempt — it is not a Nous free-tier model at all.
        if (e.role in ("primary", "fallback") and not e.local
                and not e.model.endswith(":free")):
            problems.append(f"chain[{i}] ({e.alias}) is role={e.role} on the chain provider but is "
                            f"not a free model ({e.model}) — the free tier must come first (issue #1140)")
        if not e.provider:
            problems.append(f"chain[{i}] ({e.alias}) names no provider")
        if e.base_url and not URL_RE.match(e.base_url):
            problems.append(f"chain[{i}] ({e.alias}) base_url is not a URL: {e.base_url!r}")
        if e.key_env and not ENV_NAME_RE.match(e.key_env):
            problems.append(f"chain[{i}] ({e.alias}) key_env is not an environment NAME: {e.key_env!r}")
        # Measured on issue #1199: a `nous` alias carrying `base_url`/`key_env` is re-routed to
        # the `custom` provider and answers HTTP 401 — the Nous provider supplies both itself.
        if e.provider == "nous" and (e.base_url or e.key_env):
            problems.append(f"chain[{i}] ({e.alias}) is a `nous` step but carries base_url/key_env — "
                            "they re-route it to `custom` and 401; a `nous` step carries ONLY "
                            "`provider: nous` (issue #1199)")

    if not chain.provider:
        problems.append("the chain names no provider for its aliases")
    if chain.provider == "custom" and not chain.base_url:
        problems.append("a `custom` chain provider must name its endpoint (base_url)")
    if chain.key_env and not ENV_NAME_RE.match(chain.key_env):
        problems.append(f"chain key_env is not an environment NAME: {chain.key_env!r}")

    if "HERMES_MODEL" in pins and last_resorts and last_resorts[0].model != pins["HERMES_MODEL"]:
        problems.append(
            f"the last resort is {last_resorts[0].model!r} but the Makefile pins HERMES_MODEL={pins['HERMES_MODEL']!r} "
            "— the chain's last step must be the pinned model every leg falls back to"
        )
    if "HERMES_ALIAS" in pins and last_resorts and last_resorts[0].alias != pins["HERMES_ALIAS"]:
        problems.append(
            f"the last resort alias is {last_resorts[0].alias!r} but the Makefile pins HERMES_ALIAS={pins['HERMES_ALIAS']!r} "
            "— `_setup` and `_hermes-alias-check` write and read that ONE name"
        )
    # The Makefile's alias is the CONTAINER legs' shape (`provider: custom` + NOUS_API_KEY from
    # the repository secret); the CHAIN's provider is the HOST lanes' shape (`nous`, the Portal
    # session) — issue #1199 measured the host's NOUS_API_KEY answering 401. They are the same
    # ENDPOINT, so a `custom` chain must still name the Makefile's NOUS_BASE and key_env.
    if chain.provider == "custom":
        if "NOUS_BASE" in pins and chain.base_url != pins["NOUS_BASE"]:
            problems.append(f"chain base_url {chain.base_url!r} is not the Makefile's NOUS_BASE {pins['NOUS_BASE']!r}")
        if "ALIAS_KEY_ENV" in pins and chain.key_env != pins["ALIAS_KEY_ENV"]:
            problems.append(f"chain key_env {chain.key_env!r} is not the key_env the Makefile writes for the alias ({pins['ALIAS_KEY_ENV']!r})")
    if not chain.measured.get("how"):
        problems.append("the chain names no `measured.how` — every model id in it must trace to a real read (rule 2)")
    return problems


def render_text(chain: Chain) -> str:
    """The lane profile config this chain renders — one implementation, used by --write and --check."""
    primary = chain.primary
    lines = [GENERATED_HEADER, "model:"]
    lines.append(f"  provider: {chain.provider}")
    lines.append(f"  default: {primary.model if primary else ''}")
    if chain.base_url:
        lines.append(f"  base_url: {chain.base_url}")
    if primary:
        lines.append(f"  context_length: {primary.context_window}")
    lines.append("")
    lines.append("# The chain, in the order it is used: primary, then each fallback, then the last resort.")
    lines.append("# A lane selects a step with `hermes -m <alias>`; `key_env` names the variable the")
    lines.append("# container receives, never its value (AGENTS.md rule 3e).")
    lines.append("model_aliases:")
    for e in chain.entries:
        lines.append(f"  {e.alias}:")
        lines.append(f"    model: {e.model}")
        lines.append(f"    provider: {e.provider}")
        if e.base_url:
            lines.append(f"    base_url: {e.base_url}")
        lines.append(f"    context_window: {e.context_window}")
        if e.key_env:
            lines.append(f"    key_env: {e.key_env}")
    return "\n".join(lines) + "\n"


def config_problems(root: Path, chain: Chain, rendered: str) -> list[str]:
    """Every way a lane's on-disk config can drift from the chain it was rendered from."""
    problems: list[str] = []
    lanes = fleet_lanes(root)
    if not lanes:
        return ["no fleet lane found under agents/ (agents/tll-*/SOUL.md) — nothing renders"]
    for lane in lanes:
        path = root / "agents" / lane / CONFIG_REL
        if not path.is_file():
            problems.append(f"agents/{lane}/{CONFIG_REL} is missing — `make agent-profile-model-render` writes it")
            continue
        on_disk = path.read_text()
        if on_disk != rendered:
            diff = _first_diff_line(on_disk, rendered)
            problems.append(f"agents/{lane}/{CONFIG_REL} drifted from the chain ({diff}) — re-run `make agent-profile-model-render`, never hand-edit a generated config")
    return problems


def _first_diff_line(on_disk: str, rendered: str) -> str:
    a, b = on_disk.splitlines(), rendered.splitlines()
    for i, (x, y) in enumerate(zip(a, b), start=1):
        if x != y:
            return f"line {i}: on disk {x!r} vs chain {y!r}"
    if len(a) != len(b):
        return f"line {min(len(a), len(b)) + 1}: {len(a)} lines on disk vs {len(b)} rendered"
    return "byte-for-byte equal but not identical"


def credential_leak_problems(root: Path) -> list[str]:
    """A credential VALUE, or a credential-shaped KEY, in the chain or in any lane config."""
    problems: list[str] = []
    targets = [root / CHAIN_REL] + [root / "agents" / lane / CONFIG_REL for lane in fleet_lanes(root)]
    for path in targets:
        if not path.is_file():
            continue
        try:
            text = path.read_text()
        except OSError as exc:
            problems.append(f"{path.relative_to(root)} could not be read: {exc}")
            continue
        for key in CREDENTIAL_KEYS:
            for m in re.finditer(rf"(?im)^\s*[\"']?{key}[\"']?\s*[:=]", text):
                problems.append(f"{path.relative_to(root)}:{text[:m.start()].count(chr(10)) + 1} carries a credential field {key!r} — rule 3e allows `key_env` NAMES only")
        for m in re.finditer(r"(?m)^\s*key_env:\s*(\S+)", text):
            if not ENV_NAME_RE.match(m.group(1)):
                problems.append(f"{path.relative_to(root)}:{text[:m.start()].count(chr(10)) + 1} key_env {m.group(1)!r} is not an environment NAME")
    return problems


# ------------------------------------------------------------------------- modes


def render(root: Path) -> int:
    chain, fatal = read_chain(root)
    if fatal:
        print(f"[model-chain] UNDECIDABLE: {fatal}", file=sys.stderr)
        return EXIT_UNDECIDABLE
    assert chain is not None
    pins, pin_problems = read_makefile_pins(root)
    problems = chain_problems(chain, pins)
    if problems:
        for p in problems:
            print(f"[model-chain] FAIL {p}", file=sys.stderr)
        return EXIT_PROBLEM
    rendered = render_text(chain)
    lanes = fleet_lanes(root)
    for lane in lanes:
        path = root / "agents" / lane / CONFIG_REL
        path.write_text(rendered)
    print(f"[model-chain] rendered {len(lanes)} lane config(s) from {CHAIN_REL}: "
          + " -> ".join(f"{e.alias}({e.model})" for e in chain.entries))
    return EXIT_OK


def report(root: Path) -> int:
    chain, fatal = read_chain(root)
    if fatal:
        print(f"[model-chain] UNDECIDABLE: {fatal}", file=sys.stderr)
        return EXIT_UNDECIDABLE
    assert chain is not None
    print(f"[model-chain] {len(chain.entries)} step(s), key_env={chain.key_env}")
    for i, e in enumerate(chain.entries, start=1):
        print(f"  {i}. {e.role:<11} {e.alias:<14} {e.model} ctx={e.context_window}")
    return EXIT_OK


def check(root: Path) -> int:
    chain, fatal = read_chain(root)
    if fatal:
        print(f"[model-chain] UNDECIDABLE: {fatal}", file=sys.stderr)
        return EXIT_UNDECIDABLE
    assert chain is not None
    pins, pin_problems = read_makefile_pins(root)
    problems = pin_problems + chain_problems(chain, pins) + config_problems(root, chain, render_text(chain))
    problems += credential_leak_problems(root)
    lanes = fleet_lanes(root)
    if problems:
        for p in problems:
            print(f"[model-chain] FAIL {p}", file=sys.stderr)
        return EXIT_PROBLEM
    last = chain.last_resort
    print(f"[model-chain] OK: {len(lanes)} lane config(s) render from {len(chain.entries)} chain step(s) "
          "in order " + " -> ".join(e.alias for e in chain.entries)
          + f"; last resort {last.model if last else '?'} matches the Makefile pin; credentials are NAMES only")
    return EXIT_OK


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify the chain and every lane config (default)")
    ap.add_argument("--write", action="store_true", help="render every lane config from the chain")
    ap.add_argument("--report", action="store_true", help="print the chain in order")
    ap.add_argument("--root", default=str(ROOT), help="repository root to read (tests plant a scratch tree)")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    if args.write:
        return render(root)
    if args.report:
        return report(root)
    return check(root)


if __name__ == "__main__":
    raise SystemExit(main())
