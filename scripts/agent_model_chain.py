def render(root: Path) -> int:
    chain, fatal = read_chain(root)
    if fatal:
        print(f"[model-chain] UNDECIDABLE: {fatal}", file=sys.stderr)
        return EXIT_UNDECIDABLE
    assert chain is not None
    pins, pin_problems = read_makefile_pins(root)
    problems = chain_problems(chain, pins)
    if problems:
        for p in problems:
            print(f"[model-chain] FAIL {p}", file=sys.stderr)
        return EXIT_PROBLEM
    lanes = fleet_lanes(root)
    for lane in lanes:
        path = root / "agents" / lane / CONFIG_REL
        path.write_text(render_lane(root, chain, lane))
    print(f"[model-chain] rendered {len(lanes)} lane config(s) from {CHAIN_REL}: "
          + " -> ".join(f"{e.alias}({e.model})" for e in chain.entries))
    return EXIT_OK


def report(root: Path) -> int:
    chain, fatal = read_chain(root)
    if fatal:
        print(f"[model-chain] UNDECIDABLE: {fatal}", file=sys.stderr)
        return EXIT_UNDECIDABLE
    assert chain is not None
    print(f"[model-chain] {len(chain.entries)} step(s), key_env={chain.key_env}")
    for i, e in enumerate(chain.entries, start=1):
        print(f"  {i}. {e.role:<13} {e.alias:<14} {e.model} ctx={e.context_window}")
    return EXIT_OK


def check(root: Path) -> int:
    chain, fatal = read_chain(root)
    if fatal:
        print(f"[model-chain] UNDECIDABLE: {fatal}", file=sys.stderr)
        return EXIT_UNDECIDABLE
    assert chain is not None
    pins, pin_problems = read_makefile_pins(root)
    problems = pin_problems + chain_problems(chain, pins) + config_problems(root, chain)
    problems += credential_leak_problems(root)
    lanes = fleet_lanes(root)
    if problems:
        for p in problems:
            print(f"[model-chain] FAIL {p}", file=sys.stderr)
        return EXIT_PROBLEM
    last = chain.last_resort
    print(f"[model-chain] OK: {len(lanes)} lane config(s) render from {len(chain.entries)} chain step(s) "
          "in order " + " -> ".join(e.alias for e in chain.entries)
          + f"; last resort {last.model if last else '?'} matches the Makefile pin; credentials are NAMES only")
    return EXIT_OK


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify the chain and every lane config (default)")
    ap.add_argument("--write", action="store_true", help="render every lane config from the chain")
    ap.add_argument("--report", action="store_true", help="print the chain in order")
    ap.add_argument("--root", default=str(ROOT), help="repository root to read (tests plant a scratch tree)")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    if args.write:
        return render(root)
    if args.report:
        return report(root)
    return check(root)


if __name__ == "__main__":
    raise SystemExit(main())
