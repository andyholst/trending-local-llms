#!/usr/bin/env python3
"""Generate / verify the root OpenSpec index (`OPENSPEC.md`).

`OPENSPEC.md` at the repository root is the ONE file that references every
spec-driven change this repo has ever had — active and archived — with its GitHub
issue, the capability specs it edits and its task progress. A reviewer (or an
agent starting work) opens it instead of walking `openspec/changes/` by hand.

The file is GENERATED, never hand-edited:

    make openspec-index          # rewrite OPENSPEC.md from openspec/changes/**
    make openspec-index-check    # fail when OPENSPEC.md is stale or a change is missing

`--check` re-renders from disk and fails when the committed file differs, so a
change directory that is not listed — or a row whose issue/spec/tasks data went
stale — turns the pipeline red instead of drifting silently. Both targets are
wired into `make openspec-check`, which `qa-validate` runs on every PR (rule 6d).

Layout it reads:

    openspec/changes/<name>/proposal.md          (active change)
    openspec/changes/<name>/specs/<cap>/spec.md  (its capability specs)
    openspec/changes/<name>/tasks.md             (its task checklist)
    openspec/changes/archive/<name>/…            (archived change, same shape)

Issue/PR references come from the proposal's own header lines:

    Issue: #170
    PR: #171

Usage:
    python3 scripts/openspec_index.py --write
    python3 scripts/openspec_index.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHANGES = ROOT / "openspec" / "changes"
INDEX = ROOT / "OPENSPEC.md"

MARKER = "<!-- GENERATED by scripts/openspec_index.py — edit the change, then run `make openspec-index`. -->"

_REF = re.compile(r"^(Issue|PR):\s*(.+?)\s*$", re.MULTILINE)
_TASK_BOX = re.compile(r"^\s*[-*+]\s+\[([ xX~])\]\s+", re.MULTILINE)
_LINK = re.compile(r"\[#(\d+)\]")


def _refs(proposal: Path) -> dict[str, str]:
    """`{'Issue': '#170'}` from the proposal's `Issue:` / `PR:` header lines."""
    if not proposal.is_file():
        return {}
    out: dict[str, str] = {}
    for kind, value in _REF.findall(proposal.read_text(encoding="utf-8")):
        # `Issue: [#170](https://…)` -> `#170`; a bare `Issue: #170` stays as-is.
        m = _LINK.search(value)
        out[kind] = f"#{m.group(1)}" if m else value
    return out


def _tasks(tasks: Path) -> str:
    """`3/5` for a tasks.md; `missing` when there is no checklist at all.

    A `- [~]` box (blocked on a human, issue #409) is counted in the total and
    is neither done nor dropped: it renders `3/5 · 1 blocked`, so a change whose
    only unfinished work is a person's signature stays visibly incomplete in the
    one file a reviewer opens. A checklist with no blocked box is unchanged.
    """
    if not tasks.is_file():
        return "missing"
    boxes = _TASK_BOX.findall(tasks.read_text(encoding="utf-8"))
    if not boxes:
        return "none"
    done = sum(1 for b in boxes if b.lower() == "x")
    blocked = sum(1 for b in boxes if b == "~")
    out = f"{done}/{len(boxes)}"
    return f"{out} · {blocked} blocked" if blocked else out


def _specs(change: Path) -> list[str]:
    """Relative paths of the change's capability specs, sorted."""
    base = change / "specs"
    if not base.is_dir():
        return []
    return sorted(str(p.relative_to(ROOT)) for p in base.glob("*/spec.md"))


def _row(name: str, change: Path, archived: bool) -> str:
    refs = _refs(change / "proposal.md")
    proposal = change / "proposal.md"
    prop = f"[proposal.md]({proposal.relative_to(ROOT)})" if proposal.is_file() else "—"
    specs = _specs(change)
    spec_cell = "<br>".join(f"[{s.split('/')[-2]}]({s})" for s in specs) or "—"
    issue = refs.get("Issue", "—")
    pr = refs.get("PR", "—")
    state = "archived" if archived else "active"
    return (
        f"| `{name}` | {state} | {issue} | {pr} | {spec_cell} | {_tasks(change / 'tasks.md')} | {prop} |"
    )


def discover(changes: Path | None = None) -> tuple[list[tuple[str, Path]], list[tuple[str, Path]]]:
    """(active, archived) as sorted (name, path) pairs — every change dir.

    `changes` defaults to this checkout's `openspec/changes/`; the lifecycle
    guard (`scripts/openspec_archive_check.py`) passes its own, so the layout is
    read by ONE implementation (rule 6d).
    """
    changes = changes or CHANGES
    active: list[tuple[str, Path]] = []
    archived: list[tuple[str, Path]] = []
    if not changes.is_dir():
        return active, archived
    for p in sorted(changes.iterdir()):
        if not p.is_dir():
            continue
        if p.name == "archive":
            for a in sorted(p.iterdir()):
                if a.is_dir():
                    archived.append((a.name, a))
            continue
        active.append((p.name, p))
    return active, archived


def render() -> str:
    active, archived = discover()
    lines = [
        MARKER,
        "",
        "# OpenSpec index",
        "",
        "Every spec-driven change in this repository, in one place. `make openspec-index`",
        "regenerates this file from `openspec/changes/**`; `make openspec-index-check`",
        "(run by `make openspec-check` in CI) fails when it is stale or a change is",
        "missing from it. Work starts by creating a change (`make openspec-new NAME=<name>`)",
        "and ends with every box in its `tasks.md` ticked (or explicitly marked",
        "`- [~] … — blocked: <who/why>` and reported as review-required).",
        "",
        f"Active changes: **{len(active)}** · archived: **{len(archived)}**",
        "",
    ]
    header = "| Change | State | Issue | PR | Capability specs | Tasks | Proposal |\n|---|---|---|---|---|---|---|"
    lines += ["## Active changes", "", header]
    lines += [  # `—` keeps the table well-formed (no empty cells)
        _row(name, path, False) for name, path in active
    ] or ["| _(none)_ | — | — | — | — | — | — |"]
    lines += ["", "## Archived changes", "", header]
    lines += [_row(name, path, True) for name, path in archived] or [
        "| _(none)_ | — | — | — | — | — | — |"
    ]
    lines += [
        "",
        "## How this file stays honest",
        "",
        "- It is generated: `scripts/openspec_index.py --write`. A stale file fails",
        "  `make openspec-index-check`, which `make openspec-check` runs in CI.",
        "- Every directory under `openspec/changes/` — active or archived — must appear",
        "  above; a new change with no row turns the check red.",
        "- `Tasks` is `ticked/total` from the change's `tasks.md`; `missing` means the",
        "  change has no checklist (a structure defect `openspec validate` also flags).",
        "  `· N blocked` counts boxes marked `- [~] … — blocked: <who/why>`: work that",
        "  waits on a human, so the change stays visibly incomplete instead of green.",
        "",
    ]
    return "\n".join(lines)


def _listed(text: str) -> set[str]:
    """The change names that have a row in `text`."""
    return set(re.findall(r"^\| `([^`]+)` \|", text, re.MULTILINE))


def _rows_by_name(text: str) -> dict[str, str]:
    """`{change name: its table row}` — the row is the unit of a stale index."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        m = re.match(r"^\| `([^`]+)` \|", line)
        if m:
            out[m.group(1)] = line
    return out


def _count_line(text: str) -> str:
    """The `Active changes: **N** · archived: **M**` line, verbatim."""
    m = re.search(r"^Active changes: .*$", text, re.MULTILINE)
    return m.group(0) if m else ""


def _why_stale(current: str, text: str, active, archived) -> list[str]:
    """Name what actually differs, instead of blaming a generic field set.

    The one-line drift measured on master 9b3e34c was the COUNT LINE (the rows
    were all present and identical); the old message said "rows exist but their
    data changed (issue/PR/specs/tasks)", which points a reader at the rows and
    at three fields that had not moved. A diagnosis that names the wrong cause is
    the same defect as a red check that blames the mirror (issue #293).
    """
    lines: list[str] = []
    listed = _listed(current)
    names = [n for n, _ in active + archived]
    missing = [n for n in names if n not in listed]
    extra = sorted(listed - set(names))
    if missing:
        lines.append(f"changes on disk with no row: {', '.join(missing)}")
    if extra:
        lines.append(f"rows for changes that no longer exist: {', '.join(extra)}")

    old_count, new_count = _count_line(current), _count_line(text)
    if old_count != new_count:
        lines.append(f"the count line says '{old_count or '(missing)'}', disk needs '{new_count}'")

    old_rows, new_rows = _rows_by_name(current), _rows_by_name(text)
    changed = sorted(n for n in set(old_rows) & set(new_rows) if old_rows[n] != new_rows[n])
    if changed:
        lines.append(f"rows whose data changed: {', '.join(changed)}")

    if not lines:
        # Rows and counts agree, yet the bytes differ: the prose or the header moved.
        lines.append("the file differs outside the rows and the count line — "
                     "regenerate it rather than editing it")
    return lines


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate/verify the root OpenSpec index")
    ap.add_argument("--write", action="store_true", help="rewrite OPENSPEC.md from openspec/changes/**")
    ap.add_argument("--check", action="store_true", help="fail when OPENSPEC.md is stale (default)")
    a = ap.parse_args(argv)

    text = render()
    current = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""

    if a.write:
        INDEX.write_text(text, encoding="utf-8")
        active, archived = discover()
        print(
            f"[openspec-index] wrote {INDEX.name}: {len(active)} active, {len(archived)} archived"
        )
        return 0

    if current == text:
        active, archived = discover()
        print(
            f"[openspec-index] OK {INDEX.name} is current: {len(active)} active, {len(archived)} archived"
        )
        return 0

    active, archived = discover()
    print(
        f"[openspec-index] FAIL {INDEX.name} is stale or missing "
        f"({len(active)} active, {len(archived)} archived on disk) — run `make openspec-index`",
        file=sys.stderr,
    )
    for reason in _why_stale(current, text, active, archived):
        print(f"[openspec-index]   {reason}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
