#!/usr/bin/env python3
"""Classify a merge-tree conflict in qa-validate's OpenSpec index check (issue #1822).

The merge-tree step proves that a PR's generated ``OPENSPEC.md`` is current on
master + the PR (issue #1239).  ``OPENSPEC.md`` is generated by
``make openspec-index`` and every change edits it, so when master advances
during a validate run the two sides can conflict on that generated file even
though neither author hand-edited it.  This module is the ONE verdict seam the
step uses to tell that race from a real source conflict.

``classify`` is pure: it takes the unmerged path set captured before
``git merge --abort`` and the two real git SHAs, and prints exactly one verdict:

  * ``GENERATED_ADVANCE`` -- every conflicting path is ``OPENSPEC.md`` AND
    ``git merge-base HEAD origin/master`` differs from
    ``git rev-parse origin/master`` (master really moved).  Only this shape may
    take the bounded retry, which regenerates the file with its OWNING command
    and re-runs the unchanged ``make openspec-index-check``.
  * ``REAL_CONFLICT`` -- anything else: a non-generated path, a generated
    conflict with no master advance, or no captured path at all.

Reached only through ``make merge-tree-index-classify`` (rule 6m).  No network,
no git call, no secret and no file write: the caller supplies git's own facts.
"""
from __future__ import annotations

import argparse

# The generated artifact this step owns.  Nothing else is retryable.
GENERATED_PATHS = frozenset({"OPENSPEC.md"})

GENERATED_ADVANCE = "GENERATED_ADVANCE"
REAL_CONFLICT = "REAL_CONFLICT"


def conflict_paths(conflicts: str) -> list[str]:
    """Split the workflow's comma-joined ``--diff-filter=U`` path set."""
    return [part.strip() for part in conflicts.split(",") if part.strip()]


def classify(conflicts: str, base_before: str, master_after: str) -> str:
    """Return the one verdict for this conflict.

    A missing or empty SHA is a failed git read, never proof of a race: it
    classifies as ``REAL_CONFLICT`` so the step keeps its original hard fail.
    """
    paths = conflict_paths(conflicts)
    if not paths:
        return REAL_CONFLICT
    if any(path not in GENERATED_PATHS for path in paths):
        return REAL_CONFLICT
    if not base_before or not master_after or base_before == master_after:
        return REAL_CONFLICT
    return GENERATED_ADVANCE


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--conflicts", required=True,
                        help="comma-joined unmerged paths captured before git merge --abort")
    parser.add_argument("--base-before", required=True,
                        help="git merge-base HEAD origin/master")
    parser.add_argument("--master-after", required=True,
                        help="git rev-parse origin/master")
    args = parser.parse_args()
    print(classify(args.conflicts, args.base_before, args.master_after))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
